import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {publicationBlockers} from '../scripts/publication-policy.mjs';
const config=JSON.parse(await readFile(new URL('../release-config.json',import.meta.url),'utf8'));
let checks=0;
const check=(label,candidate,expected)=>{
 const actual=publicationBlockers(candidate);
 if(expected===null)assert.deepEqual(actual,[],label);
 else for(const blocker of expected)assert.ok(actual.includes(blocker),label+': '+blocker);
 checks++;
};
check('Current owner-approved informational site can publish',config,null);
assert.equal(config.legalApproved,false);
assert.equal(config.operatorLegalQualified,false);
assert.equal(config.supportContactOperationallyVerified,false);
check('Website approval is required',{...config,publicationApproved:false},['publicationApproved']);
check('Hosting remains required',{...config,hostingVerified:false},['hostingVerified']);
check('HTTPS origin remains required',{...config,canonicalOrigin:'http://kovacompass.app'},['canonicalOrigin']);
check('Prelaunch cannot enable downloads',{...config,publicDownloadAvailable:true},['prelaunch.publicDownloadAvailable=false']);
check('Prelaunch cannot advertise a download URL',{...config,storeUrl:'https://play.google.com/store/apps/details?id=com.kova.budget'},['prelaunch.storeUrl=null']);
check('Prelaunch cannot enable sales',{...config,premium:{...config.premium,salesAvailable:true}},['prelaunch.premium.salesAvailable=false']);
check('Prelaunch cannot enable analytics',{...config,websiteAnalytics:{...config.websiteAnalytics,enabled:true}},['prelaunch.websiteAnalytics.enabled=false','websiteAnalytics.accountConfigurationVerified']);
check('Prelaunch documents must retain their draft state',{...config,legalState:'APPROVED'},['prelaunch.legalState=DRAFT_OWNER_INPUT_REQUIRED']);
const product={...config,publicationProfile:'PRODUCT_LAUNCH'};
check('Product launch still needs the unresolved qualifications',product,['operatorLegalQualified','supportContactOperationallyVerified','legalApproved']);
check('No profile defaults to the strict product policy',{...config,publicationProfile:undefined},['operatorLegalQualified','supportContactOperationallyVerified','legalApproved']);
check('Unknown profile cannot bypass approval',{...config,publicationProfile:'anything'},['publicationProfile','legalApproved']);
check('A fully qualified fixture may use the product profile',{...product,operatorLegalQualified:true,supportContactOperationallyVerified:true,legalApproved:true},null);
console.log(JSON.stringify({result:'PASS',checks,scope:'Website publication authorization is separate from product/legal qualification'}));
